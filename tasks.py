def validate_android_release_version(tag: str) -> None:
    version, build_number = release_identity()
    expected_tag = f"v{version}"
    if tag != expected_tag:
        raise Exit(
            f"Release tag {tag!r} must match the project version tag {expected_tag!r}.", code=1
        )
    if build_number < 1:
        raise Exit("Android version code must be a positive integer.", code=1)
    previous_build_number = previous_release_build_number(tag)
    if build_number <= previous_build_number:
        raise Exit(
            f"Android version code {build_number} must be greater than the prior release "
            f"version code {previous_build_number}.",
            code=1,
        )


def android_build_tool(name: str) -> str:
    executable = name + (".exe" if platform.system() == "Windows" else "")
    sdk = AndroidSDK.android_home_dir()
    if sdk is not None:
        build_tools = sdk / "build-tools"
        if build_tools.is_dir():
            for version in sorted(build_tools.iterdir(), reverse=True):
                candidate = version / executable
                if candidate.is_file():
                    return str(candidate)
    if path := shutil.which(name):
        return path
    raise Exit(f"{name} is required; install Android SDK Build Tools or add it to PATH.", code=1)


def verify_android_release_apk(apk: Path, abi: str) -> None:
    version, build_number = release_identity()
    bundle_id, _, expected_fingerprint = android_release_configuration()
    if abi not in release_tools.ANDROID_ABIS:
        raise Exit(f"Unsupported release APK architecture: {abi}.", code=1)
    expected_filename = release_tools.android_apk_names(version)[
        release_tools.ANDROID_ABIS.index(abi)
    ]
    if apk.name != expected_filename:
        raise Exit(f"Release APK must be named {expected_filename}.", code=1)
    if not apk.is_file() or apk.stat().st_size == 0:
        raise Exit("The release APK is missing or empty.", code=1)

    expected_digest = re.sub(r"[^0-9a-f]", "", expected_fingerprint.lower())
    if (
        not re.fullmatch(r"(?:[0-9a-fA-F]{2}:){31}[0-9a-fA-F]{2}", expected_fingerprint)
        or len(expected_digest) != 64
    ):
        raise Exit("The pinned Android release certificate fingerprint is invalid.", code=1)

    signer_output = capture_command(
        android_build_tool("apksigner"), "verify", "--verbose", "--print-certs", str(apk)
    )
    signer_digests = re.findall(
        r"certificate SHA-256 digest:\s*([0-9a-fA-F:]+)", signer_output, flags=re.IGNORECASE
    )
    if not signer_digests or any(
        re.sub(r"[^0-9a-f]", "", digest.lower()) != expected_digest for digest in signer_digests
    ):
        raise Exit("APK signer does not match the pinned production certificate.", code=1)

    badging = capture_command(android_build_tool("aapt"), "dump", "badging", str(apk))
    package = re.search(
        r"^package: name='([^']+)' versionCode='(\d+)' versionName='([^']+)'",
        badging,
        flags=re.MULTILINE,
    )
    if package is None:
        raise Exit("Could not read package identity and version metadata from the APK.", code=1)
    actual_bundle, actual_build, actual_version = package.groups()
    if actual_bundle != bundle_id:
        raise Exit(f"APK application ID is {actual_bundle!r}, expected {bundle_id!r}.", code=1)
    if int(actual_build) != build_number or actual_version != version:
        raise Exit(
            f"APK version metadata is {actual_version}/{actual_build}; "
            f"expected {version}/{build_number}.",
            code=1,
        )
    try:
        with ZipFile(apk) as archive:
            native_files = {
                name
                for name in archive.namelist()
                if name.startswith("lib/") and name.endswith(".so")
            }
    except (OSError, BadZipFile) as exc:
        raise Exit("Could not inspect the release APK's native libraries.", code=1) from exc
    observed_abis = {name.split("/")[1] for name in native_files}
    if observed_abis != {abi}:
        raise Exit(
            f"APK native architectures are {sorted(observed_abis)!r}; expected only {abi}.", code=1
        )
    required = {f"lib/{abi}/libapp.so", f"lib/{abi}/libflutter.so"}
    if not required <= native_files or not any(
        name.startswith(f"lib/{abi}/libpython") for name in native_files
    ):
        raise Exit("Release APK is missing the Flutter app, engine or Python runtime.", code=1)
    print(
        f"Verified {apk} ({apk.stat().st_size} bytes): {bundle_id} "
        f"{version} ({build_number}), {abi}, production signer {expected_fingerprint}."
    )


def stage_release() -> None:
    version, build = release_identity()
    (ROOT / "src/app").mkdir(parents=True, exist_ok=True)
    (ROOT / "src/app/.release.json").write_text(
        json.dumps({"version": version, "build_number": build}) + "\n", encoding="utf-8"
    )


def validate_icon() -> None:
    icon = ROOT / "assets/icon.png"
    if not icon.is_file():
        raise Exit("Missing canonical assets/icon.png; see docs/branding.md.", code=1)
    with Image.open(icon) as image:
        if image.format != "PNG" or image.size != (1024, 1024):
            raise Exit("assets/icon.png must be a 1024 x 1024 PNG.", code=1)
        image.verify()


def find_adb() -> str | None:
    if found := shutil.which("adb"):
        return found
    sdk = AndroidSDK.android_home_dir()
    if sdk is None:
        return None
    adb = sdk / "platform-tools" / ("adb.exe" if platform.system() == "Windows" else "adb")
    return str(adb) if adb.is_file() else None


def build_target(
    target: str,
    *extra: str,
    signing: bool = False,
    env: dict[str, str] | None = None,
) -> None:
    if signing and target != "apk":
        raise Exit("Production signing is supported only for Android APK builds.", code=1)
    require_host(target)
    (ROOT / "src/app/.debug-mode").unlink(missing_ok=True)
    stage_assets(linux=target == "linux", windows=target == "windows")
    execute(
        "flet",
        "build",
        target,
        UNATTENDED,
        *extra,
        env=debug_env(False) | (env or {}),
        unset_env=() if signing else ANDROID_SIGNING_ENV,
    )
    if target == "apk":
        version, _ = release_identity()
        (ROOT / "build/apk/textmoney.apk").replace(ROOT / f"build/apk/textmoney-{version}.apk")


def prepare_linux_dev_client() -> Path:
    """Brand an isolated stock client without changing Flet's shared cache."""
    import flet_desktop

    validate_icon()
    stock = flet_desktop.ensure_client_cached() / "flet"
    original = STOCK_CLIENT_APP_ID + b"\0"
    replacement = LINUX_DEV_APP_ID.encode("ascii") + b"\0"
    binary = (stock / "flet").read_bytes()
    if len(original) != len(replacement) or binary.count(original) != 1:
        raise Exit(
            "Flet Linux client identity changed; update the development icon adapter.", code=1
        )

    destination = ROOT / "build/linux-dev-client"
    if destination.is_symlink():
        raise Exit("build/linux-dev-client must not be a symlink.", code=1)
    if destination.exists():
        shutil.rmtree(destination)
    (destination / "data").mkdir(parents=True)
    (destination / "lib").symlink_to(stock / "lib", target_is_directory=True)
    for item in (stock / "data").iterdir():
        if item.name != "app_icon.png":
            (destination / "data" / item.name).symlink_to(item, target_is_directory=item.is_dir())
    icon_image = desktop_icon()
    icon_bytes = icon_image.tobytes()
    icon = destination / "data" / f"app_icon-{hashlib.sha256(icon_bytes).hexdigest()}.png"
    icon_image.save(icon)
    (destination / "data/app_icon.png").symlink_to(icon.name)
    executable = destination / "flet"
    executable.write_bytes(binary.replace(original, replacement))
    executable.chmod(0o755)

    data_home = Path(os.environ.get("XDG_DATA_HOME", str(Path.home() / ".local/share")))
    entry = data_home / "applications" / f"{LINUX_DEV_APP_ID}.desktop"
    entry.parent.mkdir(parents=True, exist_ok=True)
    root = str(ROOT).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    entry.write_text(
        "[Desktop Entry]\nType=Application\nName=TextMoney (development)\n"
        f'Exec=uv --directory "{root}" run inv run\n'
        f"Icon={icon}\nTerminal=false\nNoDisplay=true\n"
        f"StartupWMClass={LINUX_DEV_APP_ID}\n",
        encoding="utf-8",
    )
    return destination


def run_app(*, web: bool = False, debug: bool = False, port: int = 8550) -> None:
    compile_translations()
    stage_release()
    args = [
        "flet",
        "run",
        str(ROOT / "src/main.py"),
        "--recursive",
        "--assets",
        str(ROOT / "assets"),
        "--ignore-dirs",
        ".flet,__pycache__",
    ]
    if web:
        args += ["--web", "--host", "127.0.0.1", "--port", str(port)]
    if debug:
        args += ["-v"]
    env = debug_env(debug)
