def normalize_prefix(prefix: str) -> str:
    prefix = prefix.strip("/")
    if prefix and (
        not re.fullmatch(r"[A-Za-z0-9_./-]+", prefix)
        or any(part in {"", ".", ".."} for part in prefix.split("/"))
    ):
        raise Exit("Web base URL must be a relative path without dot or empty segments.", code=1)
    return prefix


