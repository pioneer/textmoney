def debug_mobile(target: str, device: str, list_devices: bool) -> None:
    require_host(target)
    if not device and not list_devices:
        raise Exit("Specify --device=DEVICE_ID or use --list-devices first.", code=1)
    stage_assets()
    args = ["flet", "debug", target, UNATTENDED, "-v", "--no-compile-app"]
    args += ["--device-id", device or "discover"]
    if list_devices:
        args += ["--show-devices"]
    marker = ROOT / "src/app/.debug-mode"
    try:
        marker.write_text("1\n", encoding="ascii")
        execute(*args, env=debug_env(True))
    finally:
        marker.unlink(missing_ok=True)


