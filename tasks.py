def execute(
    *args: str,
    env: dict[str, str] | None = None,
    cwd: Path | None = None,
    unset_env: tuple[str, ...] = (),
) -> None:
    sys.stdout.flush()
    process_env = os.environ | (env or {})
    for name in unset_env:
        process_env.pop(name, None)
    try:
        subprocess.run(args, cwd=cwd or ROOT, env=process_env, check=True)
    except FileNotFoundError as exc:
        raise Exit(f"Required command not found: {args[0]}", code=1) from exc
    except subprocess.CalledProcessError as exc:
        raise Exit(
            f"{args[0]} failed with exit code {exc.returncode}", code=exc.returncode
        ) from exc


def require_host(target: str) -> None:
    expected = "Darwin" if target in {"ipa", "ios-simulator", "ios"} else HOSTS.get(target)
    if expected and platform.system() != expected:
        raise Exit(f"{target} requires {expected}; current host is {platform.system()}.", code=1)


def debug_env(debug: bool) -> dict[str, str]:
    return {
        "APP_DEBUG": "1" if debug else "0",
        "PYTHONUNBUFFERED": "1",
        "PYTHONDONTWRITEBYTECODE": "1",
    }


def stage_assets(*, linux: bool = False, windows: bool = False) -> None:
    validate_icon()
    compile_translations()
    # Flet's exclusions match exact paths, so nested development caches can leak.
    for cache in (ROOT / "src").rglob("__pycache__"):
        if cache.is_symlink():
            cache.unlink()
        else:
            shutil.rmtree(cache)
    stage_release()
    destination = ROOT / "src/assets"
    if destination.is_symlink():
        raise Exit("src/assets must not be a symlink; it is generated by Invoke.", code=1)
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(ROOT / "assets", destination)
    for target, enabled in (("linux", linux), ("windows", windows)):
        if enabled:
            desktop_icon().save(destination / f"icon_{target}.png")


def desktop_icon() -> Image.Image:
    """Remove the Android canvas using an artwork mask, retaining dark outlines."""
    validate_icon()
    scale = 3
    mask = Image.new("L", (1024 * scale, 1024 * scale))
    draw = ImageDraw.Draw(mask)
    draw.rounded_rectangle(
        tuple(value * scale for value in (192, 160, 768, 864)),
        radius=48 * scale,
        fill=255,
    )
    draw.polygon([(x * scale, y * scale) for x, y in ((616, 160), (768, 160), (768, 312))], fill=0)
    for points in (
        ((800, 350), (898, 412), (704, 736), (572, 816), (598, 678)),
        ((808, 370), (840, 320), (908, 364), (876, 414)),
    ):
        draw.polygon([(x * scale, y * scale) for x, y in points], fill=255)
    alpha = Image.new("L", (1024, 1024))
    alpha.paste(mask.resize((664, 664), Image.Resampling.LANCZOS), (180, 180))
    with Image.open(ROOT / "assets/icon.png") as source:
        artwork = source.convert("RGBA")
    artwork.putalpha(alpha)
    bounds = alpha.getbbox()
    if bounds is None:
        raise Exit("Desktop icon has no visible artwork.", code=1)
    artwork = artwork.crop(bounds)
    factor = 944 / max(artwork.size)
    artwork = artwork.resize(
        (round(artwork.width * factor), round(artwork.height * factor)),
        Image.Resampling.LANCZOS,
    )
    result = Image.new("RGBA", (1024, 1024))
    result.paste(artwork, ((1024 - artwork.width) // 2, (1024 - artwork.height) // 2))
    return result


def release_identity() -> tuple[str, int]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return project["project"]["version"], project["tool"]["flet"]["build_number"]


def android_release_configuration() -> tuple[str, str, str]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return (
        project["tool"]["flet"]["bundle_id"],
        project["tool"]["textmoney"]["android_release"]["signing_alias"],
        project["tool"]["textmoney"]["android_release"]["certificate_sha256"],
    )


def release_setup_command(
    *args: str, body: bytes | None = None, env: dict[str, str] | None = None
) -> bytes:
    """Capture tool output so signing failures cannot expose secret inputs."""
    try:
        result = subprocess.run(
            args,
            cwd=ROOT,
            input=body,
            capture_output=True,
            env=os.environ | (env or {}),
            check=False,
        )
    except FileNotFoundError as exc:
        raise Exit(f"Required command not found: {args[0]}.", code=1) from exc
    if result.returncode:
        raise Exit(
            f"{args[0]} {args[1]} failed (exit {result.returncode}); "
            "check credentials, permissions, and tool configuration. "
            "Tool output was withheld to protect signing credentials.",
            code=1,
        )
    return result.stdout


def check_android_release_tools() -> None:
    for command in ("java", "keytool", "gh"):
        if shutil.which(command) is None:
            raise Exit(
                f"Missing {command}. On Manjaro, run in your console:\n"
                "sudo pacman -S --needed jdk17-openjdk github-cli\n"
                "Then authenticate with: gh auth login",
                code=1,
            )
    result = subprocess.run(["java", "-version"], capture_output=True, text=True, check=False)
    match = re.search(r'version "(\d+)', result.stdout + result.stderr)
    if result.returncode or match is None or int(match[1]) < 17:
        raise Exit(
            "JDK 17 or newer is required. On Manjaro, run in your console:\n"
            "sudo pacman -S --needed jdk17-openjdk\n"
            "archlinux-java status\n"
            "sudo archlinux-java set java-17-openjdk\n"
            "java -version",
            code=1,
        )
    for tool in ("apksigner", "aapt"):
        android_build_tool(tool)
    release_setup_command("gh", "auth", "status")
    print("Java, keytool, Android Build Tools, and GitHub authentication checked.")


@task
def setup_android_release(
    context: Context,
    keystore: str = "",
    upload_secrets: bool = False,
) -> None:
    """Check the production key; optionally upload signing secrets to GitHub."""
    check_android_release_tools()
    key_path = (
        Path(keystore or "~/.local/share/pioneer-signing/android-release.jks")
        .expanduser()
        .resolve()
    )
    if not key_path.is_file():
        raise Exit("Existing production keystore not found; no key was created.", code=1)
    if platform.system() != "Windows" and key_path.stat().st_mode & 0o077:
        raise Exit(
            "Keystore permissions are too broad; restrict it to its owner (chmod 600).",
            code=1,
        )
    if not sys.stdin.isatty():
        raise Exit("Run setup in an interactive terminal for private password prompts.", code=1)
    _, alias, fingerprint = android_release_configuration()
    store_password = getpass.getpass("Keystore password: ")
    key_password = getpass.getpass("Private-key password: ")
    if not store_password or not key_password:
        raise Exit("Both passwords are required; no secrets were uploaded.", code=1)
    secret_env = {
        "TEXTMONEY_SETUP_STORE_PASSWORD": store_password,
        "TEXTMONEY_SETUP_KEY_PASSWORD": key_password,
    }
    key_args = (
        "-keystore",
        str(key_path),
        "-alias",
        alias,
        "-storepass:env",
        "TEXTMONEY_SETUP_STORE_PASSWORD",
    )
    certificate = release_setup_command("keytool", "-exportcert", *key_args, env=secret_env)
    if hashlib.sha256(certificate).hexdigest() != fingerprint.replace(":", "").lower():
        raise Exit("Existing key does not match the pinned production certificate.", code=1)
    release_setup_command(
        "keytool",
        "-certreq",
        *key_args,
        "-keypass:env",
        "TEXTMONEY_SETUP_KEY_PASSWORD",
        env=secret_env,
    )
    print("Production certificate and private-key password verified; keystore unchanged.")
    if not upload_secrets:
        print("No secrets uploaded. Use --upload-secrets to configure GitHub signing secrets.")
        return
    repository = "pioneer/textmoney"
    environment = "android-production"
    release_setup_command("gh", "api", f"repos/{repository}/environments/{environment}")
    print(
        f"Target: {repository}, environment {environment}.\n"
        f"Review protection rules first: https://github.com/{repository}/settings/environments\n"
        "This replaces all three Android signing secrets; it does not change protection rules.\n"
        "Uploads are not atomic; if one fails, rerun setup to finish all three."
    )
    if input("Type UPLOAD to confirm: ").strip() != "UPLOAD":
        raise Exit("Cancelled; no signing secrets were uploaded.", code=1)
    secrets = {
        "ANDROID_KEYSTORE_BASE64": b64encode(key_path.read_bytes()),
        "ANDROID_KEYSTORE_PASSWORD": store_password.encode(),
        "ANDROID_KEY_PASSWORD": key_password.encode(),
    }
    for name, value in secrets.items():
        release_setup_command(
            "gh",
            "secret",
            "set",
            name,
            "--repo",
            repository,
            "--env",
            environment,
            body=value,
        )
        print(f"Uploaded {name}.")
    print("Signing secrets configured. No APK built, tag pushed, or release published.")


def validate_android_signing_environment() -> dict[str, str]:
    values = {name: os.environ.get(name, "").strip() for name in ANDROID_SIGNING_ENV}
    missing = [name for name, value in values.items() if not value]
    if missing:
        raise Exit(
            "Production signing is not configured; missing environment variable(s): "
            + ", ".join(missing),
            code=1,
        )

    bundle_id, expected_alias, _ = android_release_configuration()
    if values["FLET_ANDROID_SIGNING_KEY_ALIAS"] != expected_alias:
        raise Exit(
            f"Production signing alias must be {expected_alias!r} for {bundle_id}.",
            code=1,
        )
    keystore = Path(values["FLET_ANDROID_SIGNING_KEY_STORE"]).expanduser()
    if not keystore.is_file():
        raise Exit(
            "The configured Android release keystore does not exist or is not a file.", code=1
        )
    values["FLET_ANDROID_SIGNING_KEY_STORE"] = str(keystore)
    return values


def capture_command(*args: str) -> str:
    try:
        result = subprocess.run(args, capture_output=True, text=True, check=False)
    except FileNotFoundError as exc:
        raise Exit(f"Required command not found: {args[0]}", code=1) from exc
    if result.returncode:
        raise Exit(f"{args[0]} failed with exit code {result.returncode}.", code=result.returncode)
    return result.stdout


def previous_release_build_number(tag: str) -> int:
    repository = os.environ.get("GITHUB_REPOSITORY", "").strip()
    if not repository:
        repository = capture_command(
            "gh", "repo", "view", "--json", "nameWithOwner", "--jq", ".nameWithOwner"
        ).strip()
    try:
        releases = json.loads(
            capture_command(
                "gh",
                "release",
                "list",
                "--limit",
                "100",
                "--json",
                "tagName,isDraft,isPrerelease",
            )
        )
    except json.JSONDecodeError as exc:
        raise Exit("GitHub returned invalid release metadata.", code=1) from exc
    if not isinstance(releases, list):
        raise Exit("GitHub returned an invalid release list.", code=1)
    if any(
        isinstance(release, dict)
        and release.get("tagName") == tag
        and release.get("isDraft") is False
        and release.get("isPrerelease") is False
        for release in releases
    ):
        raise Exit(f"Release tag {tag} is already published; refusing to rebuild it.", code=1)
    previous_tag = next(
        (
            release["tagName"]
            for release in releases
            if isinstance(release, dict)
            and isinstance(release.get("tagName"), str)
            and release["tagName"] != tag
            and release.get("isDraft") is False
            and release.get("isPrerelease") is False
        ),
        None,
    )
    if previous_tag is None:
        raise Exit("Could not find a prior published stable GitHub Release.", code=1)

    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise Exit("Could not determine a valid GitHub repository identifier.", code=1)
    content = capture_command(
        "gh",
        "api",
        f"repos/{repository}/contents/pyproject.toml?ref={previous_tag}",
        "--jq",
        ".content",
    )
    try:
        encoded_content = "".join(content.split())
        previous_project = tomllib.loads(b64decode(encoded_content, validate=True).decode("utf-8"))
        build_number = previous_project["tool"]["flet"]["build_number"]
        previous_bundle_id = previous_project["tool"]["flet"]["bundle_id"]
    except (KeyError, ValueError, UnicodeDecodeError) as exc:
        raise Exit(
            f"Could not read the Android version code from prior release {previous_tag}.", code=1
        ) from exc
    if not isinstance(build_number, int) or build_number < 1:
        raise Exit(f"Prior release {previous_tag} has an invalid Android version code.", code=1)
    current_bundle_id, _, _ = android_release_configuration()
    if previous_bundle_id != current_bundle_id and not (
        previous_tag == "v0.3.15"
        and previous_bundle_id == "com.pioneer.txncount"
        and current_bundle_id == "com.pioneer.textmoney"
        and build_number == 38
        and previous_project.get("tool", {}).get("txncount", {}).get("android_release", {})
        == tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["tool"][
            "textmoney"
        ]["android_release"]
    ):
        raise Exit(
            f"Android application ID changed since prior release {previous_tag}; "
            "in-place updates cannot be verified.",
            code=1,
        )
    return build_number


