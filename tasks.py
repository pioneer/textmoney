@task
def clean(context: Context) -> None:
    """Remove generated output and caches, never the uv environment or source assets."""
    (ROOT / "src/app/.debug-mode").unlink(missing_ok=True)
    (ROOT / "src/app/.release.json").unlink(missing_ok=True)
    for relative in ("build", "dist", "src/assets", ".pytest_cache", ".ruff_cache", ".pyright"):
        path = ROOT / relative
        if path.is_symlink():
            path.unlink()
        elif path.exists():
            shutil.rmtree(path)
    for base in (ROOT / "src", ROOT / "tests"):
        for path in base.rglob("__pycache__"):
            shutil.rmtree(path)
    shutil.rmtree(ROOT / "__pycache__", ignore_errors=True)


@task
def build_local(context: Context) -> None:
    """Build the native desktop target for this host."""
    target = next((name for name, host in HOSTS.items() if host == platform.system()), None)
    if target is None:
        raise Exit(f"Unsupported host: {platform.system()}", code=1)
    build_target(target)


def normalize_prefix(prefix: str) -> str:
    prefix = prefix.strip("/")
    if prefix and (
        not re.fullmatch(r"[A-Za-z0-9_./-]+", prefix)
        or any(part in {"", ".", ".."} for part in prefix.split("/"))
    ):
        raise Exit("Web base URL must be a relative path without dot or empty segments.", code=1)
    return prefix


