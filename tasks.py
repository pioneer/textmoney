def execute(*args: str, env: dict[str, str] | None = None, cwd: Path | None = None) -> None:
    sys.stdout.flush()
    try:
        subprocess.run(args, cwd=cwd or ROOT, env=os.environ | (env or {}), check=True)
    except FileNotFoundError as exc:
        raise Exit(f"Required command not found: {args[0]}", code=1) from exc
    except subprocess.CalledProcessError as exc:
        raise Exit(
            f"{args[0]} failed with exit code {exc.returncode}", code=exc.returncode
        ) from exc


def require_host(target: str) -> None:
    expected = "Darwin" if target in {"ipa", "ios-simulator", "ios"} else HOSTS.get(target)
    if expected and platform.system() != expected:
        raise Exit(f"{target} requires {expected}; current host is {platform.system()}.", code=1)


def debug_env(debug: bool) -> dict[str, str]:
    return {
        "APP_DEBUG": "1" if debug else "0",
        "PYTHONUNBUFFERED": "1",
        "PYTHONDONTWRITEBYTECODE": "1",
    }


def stage_assets(*, linux: bool = False) -> None:
    validate_icon()
    compile_translations()
    # Flet's exclusions match exact paths, so nested development caches can leak.
    for cache in (ROOT / "src").rglob("__pycache__"):
        if cache.is_symlink():
            cache.unlink()
        else:
            shutil.rmtree(cache)
    stage_release()
    destination = ROOT / "src/assets"
    if destination.is_symlink():
        raise Exit("src/assets must not be a symlink; it is generated by Invoke.", code=1)
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(ROOT / "assets", destination)
    if linux:
        linux_icon().save(destination / "icon_linux.png")


def linux_icon() -> Image.Image:
    """Remove the Android canvas using an artwork mask, retaining dark outlines."""
    validate_icon()
    scale = 3
    mask = Image.new("L", (1024 * scale, 1024 * scale))
    draw = ImageDraw.Draw(mask)
    draw.rounded_rectangle(
        tuple(value * scale for value in (192, 160, 768, 864)),
        radius=48 * scale,
        fill=255,
    )
    draw.polygon([(x * scale, y * scale) for x, y in ((616, 160), (768, 160), (768, 312))], fill=0)
    for points in (
        ((800, 350), (898, 412), (704, 736), (572, 816), (598, 678)),
        ((808, 370), (840, 320), (908, 364), (876, 414)),
    ):
        draw.polygon([(x * scale, y * scale) for x, y in points], fill=255)
    alpha = Image.new("L", (1024, 1024))
    alpha.paste(mask.resize((664, 664), Image.Resampling.LANCZOS), (180, 180))
    with Image.open(ROOT / "assets/icon.png") as source:
        artwork = source.convert("RGBA")
    artwork.putalpha(alpha)
    bounds = alpha.getbbox()
    if bounds is None:
        raise Exit("Linux icon has no visible artwork.", code=1)
    artwork = artwork.crop(bounds)
    factor = 944 / max(artwork.size)
    artwork = artwork.resize(
        (round(artwork.width * factor), round(artwork.height * factor)),
        Image.Resampling.LANCZOS,
    )
    result = Image.new("RGBA", (1024, 1024))
    result.paste(artwork, ((1024 - artwork.width) // 2, (1024 - artwork.height) // 2))
    return result


def release_identity() -> tuple[str, int]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return project["project"]["version"], project["tool"]["flet"]["build_number"]


def stage_release() -> None:
    version, build = release_identity()
    (ROOT / "src/app").mkdir(parents=True, exist_ok=True)
    (ROOT / "src/app/.release.json").write_text(
        json.dumps({"version": version, "build_number": build}) + "\n", encoding="utf-8"
    )


def validate_icon() -> None:
    icon = ROOT / "assets/icon.png"
    if not icon.is_file():
        raise Exit("Missing canonical assets/icon.png; see docs/branding.md.", code=1)
    with Image.open(icon) as image:
        if image.format != "PNG" or image.size != (1024, 1024):
            raise Exit("assets/icon.png must be a 1024 x 1024 PNG.", code=1)
        image.verify()


def find_adb() -> str | None:
    if found := shutil.which("adb"):
        return found
    sdk = AndroidSDK.android_home_dir()
    if sdk is None:
        return None
    adb = sdk / "platform-tools" / ("adb.exe" if platform.system() == "Windows" else "adb")
    return str(adb) if adb.is_file() else None


def build_target(target: str, *extra: str) -> None:
    require_host(target)
    (ROOT / "src/app/.debug-mode").unlink(missing_ok=True)
    stage_assets(linux=target == "linux")
    execute("flet", "build", target, UNATTENDED, *extra, env=debug_env(False))
    if target == "apk":
        version, _ = release_identity()
        (ROOT / "build/apk/txncount.apk").replace(ROOT / f"build/apk/txncount-{version}.apk")


def prepare_linux_dev_client() -> Path:
    """Brand an isolated stock client without changing Flet's shared cache."""
    import flet_desktop

    validate_icon()
    stock = flet_desktop.ensure_client_cached() / "flet"
    original = STOCK_CLIENT_APP_ID + b"\0"
    replacement = LINUX_DEV_APP_ID.encode("ascii") + b"\0"
    binary = (stock / "flet").read_bytes()
    if len(original) != len(replacement) or binary.count(original) != 1:
        raise Exit(
            "Flet Linux client identity changed; update the development icon adapter.", code=1
        )

    destination = ROOT / "build/linux-dev-client"
    if destination.is_symlink():
        raise Exit("build/linux-dev-client must not be a symlink.", code=1)
    if destination.exists():
        shutil.rmtree(destination)
    (destination / "data").mkdir(parents=True)
    (destination / "lib").symlink_to(stock / "lib", target_is_directory=True)
    for item in (stock / "data").iterdir():
        if item.name != "app_icon.png":
            (destination / "data" / item.name).symlink_to(item, target_is_directory=item.is_dir())
    icon_image = linux_icon()
    icon_bytes = icon_image.tobytes()
    icon = destination / "data" / f"app_icon-{hashlib.sha256(icon_bytes).hexdigest()}.png"
    icon_image.save(icon)
    (destination / "data/app_icon.png").symlink_to(icon.name)
    executable = destination / "flet"
    executable.write_bytes(binary.replace(original, replacement))
    executable.chmod(0o755)

    data_home = Path(os.environ.get("XDG_DATA_HOME", str(Path.home() / ".local/share")))
    entry = data_home / "applications" / f"{LINUX_DEV_APP_ID}.desktop"
    entry.parent.mkdir(parents=True, exist_ok=True)
    root = str(ROOT).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    entry.write_text(
        "[Desktop Entry]\nType=Application\nName=TxnCount (development)\n"
        f'Exec=uv --directory "{root}" run inv run\n'
        f"Icon={icon}\nTerminal=false\nNoDisplay=true\n"
        f"StartupWMClass={LINUX_DEV_APP_ID}\n",
        encoding="utf-8",
    )
    return destination


def run_app(*, web: bool = False, debug: bool = False, port: int = 8550) -> None:
    compile_translations()
    stage_release()
    args = [
        "flet",
        "run",
        str(ROOT / "src/main.py"),
        "--recursive",
        "--assets",
        str(ROOT / "assets"),
        "--ignore-dirs",
        ".flet,__pycache__",
    ]
    if web:
        args += ["--web", "--host", "127.0.0.1", "--port", str(port)]
    if debug:
        args += ["-v"]
    env = debug_env(debug)
    if not web and platform.system() == "Linux":
        env["FLET_VIEW_PATH"] = str(prepare_linux_dev_client())
        env["FLET_APP_ID"] = LINUX_DEV_APP_ID
        # Flet prefers cwd/build/linux over FLET_VIEW_PATH, even during hot reload.
        execute(*args, env=env, cwd=ROOT / "src")
    else:
        execute(*args, env=env)


